/// Returns the virtual key code of a Keyboard/Keypad page usage, if it has
/// one.
pub(super) fn virtual_key(usage: u8) -> Option<u16> {
    KEYS.iter()
        .find(|(key, _)| *key == usage)
        .map(|&(_, code)| code)
}

/// Returns the Keyboard/Keypad page usage of a virtual key code, if it is
/// one of a key QDP sends.
pub(crate) fn usage(virtual_key: u16) -> Option<u8> {
    KEYS.iter()
        .find(|(_, code)| *code == virtual_key)
        .map(|&(usage, _)| usage)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Usages map to the `kVK_*` codes, and each usage appears once.
    #[test]
    fn maps_usages() {
        assert_eq!(virtual_key(0x04), Some(0x00)); // kVK_ANSI_A
        assert_eq!(virtual_key(0x28), Some(0x24)); // kVK_Return
        assert_eq!(virtual_key(0x52), Some(0x7e)); // kVK_UpArrow
        assert_eq!(virtual_key(0xe3), Some(0x37)); // kVK_Command
        assert_eq!(virtual_key(0xe7), Some(0x36)); // kVK_RightCommand
        assert_eq!(virtual_key(0x00), None);
        assert_eq!(usage(0x24), Some(0x28));
        assert_eq!(usage(0x36), Some(0xe7));
        assert_eq!(usage(0xffff), None);
        let mut usages: Vec<u8> = KEYS.iter().map(|&(usage, _)| usage).collect();
        let count = usages.len();
        usages.dedup();
        assert_eq!(usages.len(), count);
    }
}
