// Ember, QDP's own palette, generated from the seed #FF6A3D with Material
// Color Utilities' content scheme (Material Theme Builder's "color match"),
// at standard, medium and high contrast. The seed itself is the primary
// container; coral sits near the error red, so errors always pair their
// color with an icon and words.

/** The contrast a scheme is made for, as the system's contrast setting asks. */
enum class Contrast {
    /** The default contrast. */
    STANDARD,

    /** Medium contrast. */
    MEDIUM,

    /** High contrast. */
    HIGH,
}

/** Returns Ember's scheme for [dark] or light theme at [contrast]. */
fun emberColorScheme(dark: Boolean, contrast: Contrast): ColorScheme = when (contrast) {
    Contrast.STANDARD -> if (dark) EmberDark else EmberLight
    Contrast.MEDIUM -> if (dark) EmberDarkMediumContrast else EmberLightMediumContrast
    Contrast.HIGH -> if (dark) EmberDarkHighContrast else EmberLightHighContrast
}

