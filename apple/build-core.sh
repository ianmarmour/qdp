#!/usr/bin/env bash
# Builds the Apple apps' Rust core, libqdp_apple.a, for iPhones and iPads,
# the iOS simulator and Macs with Apple silicon, into
# apple/Generated/QDPCore.xcframework, which Swift imports as QDPCore, and
# writes the system libraries and frameworks the core links against into
# apple/Generated/QDPCore.xcconfig, which the app targets include.
#
# It needs Xcode and Rust's aarch64-apple-ios, aarch64-apple-ios-sim and
# aarch64-apple-darwin targets (rustup target add ...).
set -euo pipefail

root=$(cd "$(dirname "$0")/.." && pwd)
out="$root/apple/Generated"
# The oldest systems the apps run on, which the core is built for too.
export IPHONEOS_DEPLOYMENT_TARGET=26.0
export MACOSX_DEPLOYMENT_TARGET=26.0

# Builds the core for target $1, and prints the linker flags it needs.
build() {
    local log
    log=$(mktemp)
    CARGO_TERM_COLOR=never cargo rustc --manifest-path "$root/Cargo.toml" -p qdp-apple --lib --release \
        --target "$1" --crate-type staticlib -- --print native-static-libs 2>&1 | tee "$log" >&2
    # Without colour, but in case a terminal's escapes slipped in anyway.
    sed -n 's/.*native-static-libs: //p' "$log" | tail -n 1 | sed "s/$(printf '\033')\[[0-9;]*m//g"
    rm -f "$log"
}

ios_flags=$(build aarch64-apple-ios)
simulator_flags=$(build aarch64-apple-ios-sim)
mac_flags=$(build aarch64-apple-darwin)

rm -rf "$out"
mkdir -p "$out/include/QDPCore"
cp "$root/crates/qdp-apple/include/qdp.h" "$out/include/QDPCore/qdp.h"
cat > "$out/include/QDPCore/module.modulemap" <<'MODULE'
module QDPCore {
    header "qdp.h"
    export *
}
MODULE

xcodebuild -create-xcframework \
    -library "$root/target/aarch64-apple-ios/release/libqdp_apple.a" -headers "$out/include" \
    -library "$root/target/aarch64-apple-ios-sim/release/libqdp_apple.a" -headers "$out/include" \
    -library "$root/target/aarch64-apple-darwin/release/libqdp_apple.a" -headers "$out/include" \
    -output "$out/QDPCore.xcframework"

cat > "$out/QDPCore.xcconfig" <<CONFIG
// The libraries and frameworks the Rust core links against, as rustc
// reported them; generated by apple/build-core.sh.
OTHER_LDFLAGS[sdk=iphoneos*] = \$(inherited) $ios_flags
OTHER_LDFLAGS[sdk=iphonesimulator*] = \$(inherited) $simulator_flags
OTHER_LDFLAGS[sdk=macosx*] = \$(inherited) $mac_flags
CONFIG

echo "built $out/QDPCore.xcframework"
